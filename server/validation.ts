/**
 * server/validation.ts — request validation at the boundary.
 *
 * AGENTS.md section 19: never trust `await request.json()`. Every body, query param and
 * path param is parsed with a zod schema here, and the request/response TypeScript types
 * are inferred from those schemas so the shapes cannot drift apart.
 *
 * `parseJson` deliberately returns a plain `AppError` (400 `bad_request`) rather than
 * letting zod errors bubble, keeping the public error envelope identical everywhere.
 */

import { z } from 'zod';
import {
  ALL_CHAOS_MODES,
  ALL_TOOL_NAMES,
  COMMAND_KIND,
  CONTRACT_CHECK,
} from './constants';
import { badRequest } from './errors';

// ─────────────────────────────────────────────────────────────────────────────
// Shared primitives
// ─────────────────────────────────────────────────────────────────────────────

/** Run ids are generated by `server/runs.ts`: 8 characters, URL-safe and unambiguous. */
export const runIdSchema = z
  .string()
  .regex(/^[0-9a-z_-]{1,32}$/, 'must be a run id');

/** Budgets are optional everywhere; the worker fills the gaps from server/config.ts. */
export const budgetSchema = z
  .object({
    maxSteps: z.number().int().positive().max(50).optional(),
    maxSeconds: z.number().int().positive().max(3_600).optional(),
    maxLlmCalls: z.number().int().positive().max(200).optional(),
  })
  .strict();

// ─────────────────────────────────────────────────────────────────────────────
// Route bodies
// ─────────────────────────────────────────────────────────────────────────────

export const createRunSchema = z
  .object({
    goal: z.string().trim().min(8, 'goal must be at least 8 characters').max(2_000),
    budget: budgetSchema.optional(),
  })
  .strict();

export const authSchema = z.object({ code: z.string().min(1) }).strict();

export const commandSchema = z
  .object({
    kind: z.enum([COMMAND_KIND.pause, COMMAND_KIND.resume, COMMAND_KIND.stop, COMMAND_KIND.redirect]),
    payload: z.record(z.string(), z.unknown()).optional(),
    source: z.enum(['console', 'phone']).optional(),
  })
  .strict();

export const chaosSchema = z
  .object({
    tool: z.enum(ALL_TOOL_NAMES as unknown as [string, ...string[]]),
    mode: z.enum(ALL_CHAOS_MODES as unknown as [string, ...string[]]),
    count: z.number().int().min(1).max(5).optional(),
  })
  .strict();

export const tamperSchema = z
  .object({
    seq: z.number().int().positive(),
    payload: z.string(),
  })
  .strict();

export const bundleVerifySchema = z
  .object({
    runId: z.string().min(1),
    head: z.string().regex(/^[0-9a-f]{64}$/),
    events: z.array(
      z.object({
        seq: z.number().int().positive(),
        ts: z.number(),
        type: z.string().min(1),
        payload: z.string(),
        prevHash: z.string(),
        hash: z.string(),
      }),
    ),
  })
  .strict();

// ─────────────────────────────────────────────────────────────────────────────
// Contract criteria (produced by the model, therefore untrusted input)
// ─────────────────────────────────────────────────────────────────────────────

export const criterionSchema = z.object({
  id: z.string().min(1).max(16),
  text: z.string().min(1).max(300),
  check: z.enum([
    CONTRACT_CHECK.minUrls,
    CONTRACT_CHECK.wordRange,
    CONTRACT_CHECK.fileExists,
    CONTRACT_CHECK.llm,
  ]),
  arg: z.union([z.number(), z.string(), z.array(z.number()), z.null()]).optional(),
});

export const contractSchema = z.object({
  criteria: z.array(criterionSchema).min(1).max(6),
});

export const planStepSchema = z.object({
  step_no: z.number().int().positive(),
  title: z.string().min(1).max(160),
  tool: z.string().min(1).max(40),
});

export const planSchema = z.object({
  steps: z.array(planStepSchema).min(1).max(12),
});

export type CreateRunInput = z.infer<typeof createRunSchema>;
export type CommandInput = z.infer<typeof commandSchema>;
export type ChaosInput = z.infer<typeof chaosSchema>;
export type TamperInput = z.infer<typeof tamperSchema>;
export type ContractInput = z.infer<typeof contractSchema>;
export type CriterionInput = z.infer<typeof criterionSchema>;
export type PlanInput = z.infer<typeof planSchema>;
export type PlanStepInput = z.infer<typeof planStepSchema>;
export type BundleInput = z.infer<typeof bundleVerifySchema>;

// ─────────────────────────────────────────────────────────────────────────────
// Helpers used by route handlers
// ─────────────────────────────────────────────────────────────────────────────

/**
 * Read and validate a JSON body.
 * @throws AppError 400 `bad_request` when the body is not JSON or fails the schema.
 */
export async function parseJson<S extends z.ZodType>(
  request: Request,
  schema: S,
): Promise<z.infer<S>> {
  let raw: unknown;
  try {
    raw = await request.json();
  } catch {
    throw badRequest('Request body must be valid JSON');
  }
  return parseWith(schema, raw);
}

/**
 * Read the `?after=<seq>` cursor used by the events polling endpoint.
 *
 * A missing cursor means "from the beginning", so the first poll of a run gets its whole
 * history and every later poll asks only for what is new.
 *
 * @throws AppError 400 `bad_request` when the cursor is present but not a non-negative integer.
 */
export function readAfterSeq(request: Request): number {
  const raw = new URL(request.url).searchParams.get('after');
  if (raw === null || raw === '') return 0;

  const value = Number.parseInt(raw, 10);
  if (!Number.isInteger(value) || value < 0) {
    throw badRequest('Query parameter `after` must be a non-negative integer');
  }
  return value;
}

/** Validate an already-parsed value (used for query params and worker-private data). */
export function parseWith<S extends z.ZodType>(schema: S, value: unknown): z.infer<S> {
  const result = schema.safeParse(value);
  if (!result.success) {
    const message = result.error.issues
      .map((issue) => `${issue.path.join('.') || 'value'}: ${issue.message}`)
      .join('; ');
    throw badRequest(message);
  }
  return result.data;
}
